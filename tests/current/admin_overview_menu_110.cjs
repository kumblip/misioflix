'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const html=fs.readFileSync(path.resolve(__dirname,'../../src/Jellyfin.Plugin.MisioFlix/Web/overviewPage.html'),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/i)?.[1];
assert(script,'Overview landing page must have router code');
new vm.Script(script);
const events={};
const view={addEventListener(name,fn){events[name]=fn;}};
const location={hash:'#/configurationpage?name=MisioFlixOverview'};
vm.runInNewContext(script,{document:{getElementById(id){assert.equal(id,'misioflixOverviewPage');return view;}},window:{location}});
assert.equal(location.hash,'#/configurationpage?name=MisioFlixOverview','Must not redirect before page is active');
assert.equal(typeof events.pageshow,'function','Jellyfin page event must be wired');
events.pageshow();
assert.equal(location.hash,'#/dashboard/plugins/97d15b37b868492b83daeb67b16a0d44?name=MisioFlix');
events.pageshow();
assert.equal(location.hash,'#/dashboard/plugins/97d15b37b868492b83daeb67b16a0d44?name=MisioFlix');
console.log('PASS native admin menu: overview route, page activation, stable navigation');
