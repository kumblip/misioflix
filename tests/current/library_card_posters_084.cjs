// Regression: original Jellyfin 12.4 cards use an <img>, not a CSS poster background.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const web=path.join(__dirname,'../../src/Jellyfin.Plugin.MisioFlix/Web');
const source=fs.readFileSync(path.join(web,'library-scroll.js'),'utf8');
const client=fs.readFileSync(path.join(web,'client.js'),'utf8');
const style=fs.readFileSync(path.join(web,'theme.css'),'utf8');
const begin=source.indexOf('  function imageUrl(');
const end=source.indexOf('  function installPoster(',begin);
assert(begin>0&&end>begin,'poster source helpers found');
const ctx={};vm.createContext(ctx);
vm.runInContext("const guid = value => String(value || '').replace(/-/g, '').toLowerCase();",ctx);
vm.runInContext(source.slice(begin,end),ctx);
const item={Id:'b'.repeat(32),Type:'Series',Name:'example',ImageTags:{Primary:'tag-2026',Thumb:'thumb-tag'}};
const list=vm.runInContext(`imageCandidates(${JSON.stringify(item)})`,ctx);
assert.equal(list.length,2);
assert(list[0].includes('/Items/'+'b'.repeat(32)+'/Images/Primary?'));
assert(list[0].includes('tag=tag-2026'));
assert(list[1].includes('/Images/Thumb?'));
const tagless=vm.runInContext(`imageCandidates(${JSON.stringify({Id:'c'.repeat(32),Type:'Series'})})`,ctx);
assert.equal(tagless.length,1);
assert(tagless[0].includes('/Images/Primary?'),'fall back when lightweight API omits ImageTags');
assert(source.includes('surface.replaceChildren();'),'no previously cloned image or pink count remains');
assert(source.includes('image.className=\'mf-library-cover-img\''),'new image is an actual img element');
assert(source.includes('image.loading=\'lazy\''),'poster lazy loading');
assert(source.includes('node.setAttribute(\'data-mf-anime\',\'1\')'),'AnimePL gets proper kind immediately');
assert(source.includes('for(const link of node.querySelectorAll(\'a[href]\'))'),'all cloned hrefs target the new item');
assert(source.includes("new CustomEvent('misioflix-library-cards-added'"),'inform the existing metadata engine');
assert(client.includes("window.addEventListener('misioflix-library-cards-added'"),'existing metadata engine subscribes');
assert(client.includes('queueMetadata(card);'),'MAL, NFO, Simkl metadata via existing path');
assert(client.includes('const added=card.matches?.(\'.mf-library-extra-deck .card[data-mf-library-infinite-card="1"]\')'),'mixed-route metadata guard allows extra cards');
assert(style.includes('.mf-library-extra-deck .mf-library-cover-img'),'poster CSS scoped to extra cards');
assert(!style.includes('align-content:flex-start;gap:1em;padding-top:1.2em'),'extra deck does not add a second gap to native flex layout');
assert(source.includes('function pageParams(') && source.includes("result.StartIndex=String(offset)"),'paging v0.4.83 untouched');
console.log('PASS v0.4.84: image tag, no template posters/counts, real links, native metadata bridge and React guard');
